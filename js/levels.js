//  P  start           T  the blue tree   C  checkpoint     ?  sign
//  G  exit            K  the tank        B  mini-boss      M  the Evil Mech
//  L  lift (moves 96px)                  l  lift (moves 48px)
//  R  village house (3 tiles wide, its roof is a ledge)
//  X  the Life (the blue box)
//  m  met   b  heli-bot   j  shield joe   c  crawler   t  turret   h  hopper
//  e  small energy   E  big energy   1  extra life

