const ORDER = Object.keys(GLYPHS);
const INDEX = new Map(ORDER.map((c, i) => [c, i]));
const atlases = new Map();

function atlas(color) {
  let a = atlases.get(color);
  if (a) return a;
  a = document.createElement('canvas');
  a.width = ORDER.length * 6;
  a.height = 7;
  const c = a.getContext('2d');
  c.fillStyle = color;
  ORDER.forEach((ch, i) => {
    GLYPHS[ch].forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '1') c.fillRect(i * 6 + x, y, 1, 1);
    });
  });
  atlases.set(color, a);
  return a;
}

export function textWidth(text, scale = 1) {
  return text.length ? (text.length * 6 - 1) * scale : 0;
}

export function drawText(ctx, text, x, y, color = '#fcfcfc', opts = {}) {
  const scale = opts.scale || 1;
  text = String(text).toUpperCase();
  if (opts.align === 'center') x -= Math.floor(textWidth(text, scale) / 2);
  else if (opts.align === 'right') x -= textWidth(text, scale);
  x = Math.round(x);
  y = Math.round(y);
  if (opts.shadow) drawText(ctx, text, x + scale, y + scale, opts.shadow, { scale });
  const a = atlas(color);
  for (let i = 0; i < text.length; i++) {
    const g = INDEX.get(text[i]);
    if (g !== undefined) ctx.drawImage(a, g * 6, 0, 5, 7, x + i * 6 * scale, y, 5 * scale, 7 * scale);
  }
}

// Break text into lines of at most `max` characters, on spaces.
export function wrap(text, max) {
  const lines = [];
  for (const para of String(text).toUpperCase().split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      if (!line) line = word;
      else if (line.length + 1 + word.length <= max) line += ' ' + word;
      else { lines.push(line); line = word; }
    }
    lines.push(line);
  }
  return lines;
}
